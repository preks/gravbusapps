function propName(locale: string) {
  // en-US -> enUS
  return locale.replace('-', '').replace(/([a-z]{2})([A-Z]{2})/, (_, a, b) => a + b)
}

export function generateSimpleIndex(i18nDir: string, locales: string[], importParentRelative: string) {
  const imports = [`import translations from '${importParentRelative}';`]
  for (const lc of locales) {
    imports.push(`import ${propName(lc)} from './${lc}.ftl?raw';`)
  }
  const lines = locales
    .map(lc => `  ${propName(lc)}: translations.${propName(lc)} + '\n' + ${propName(lc)},`)
    .join('\n')
  const type = `as { ${locales.map(lc => propName(lc) + ': string').join('; ')} }`
  return `// AUTO-GENERATED by I18n Admin (simple aggregator)
${imports.join('\n')}

export default {
${lines}
} ${type};
`
}
