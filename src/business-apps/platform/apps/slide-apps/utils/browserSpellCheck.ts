function levenshteinDistance(a: string, b: string): number {
  const matrix: number[][] = []

  for (let i = 0; i <= b.length; i++) {
    matrix[i] = [i]
  }

  for (let j = 0; j <= a.length; j++) {
    matrix[0][j] = j
  }

  for (let i = 1; i <= b.length; i++) {
    for (let j = 1; j <= a.length; j++) {
      if (b.charAt(i - 1) === a.charAt(j - 1)) {
        matrix[i][j] = matrix[i - 1][j - 1]
      } else {
        matrix[i][j] = Math.min(matrix[i - 1][j - 1] + 1, matrix[i][j - 1] + 1, matrix[i - 1][j] + 1)
      }
    }
  }

  return matrix[b.length][a.length]
}

function findSuggestions(word: string, maxDistance = 2, maxSuggestions = 3): string[] {
  const lowerWord = word.toLowerCase()

  if (COMMON_MISSPELLINGS[lowerWord]) {
    return [COMMON_MISSPELLINGS[lowerWord]]
  }

  const suggestions: { word: string; distance: number }[] = []

  for (const dictWord of COMMON_WORDS) {
    if (Math.abs(dictWord.length - lowerWord.length) > maxDistance) continue

    const distance = levenshteinDistance(lowerWord, dictWord)
    if (distance <= maxDistance) {
      suggestions.push({ word: dictWord, distance })
    }
  }

  suggestions.sort((a, b) => a.distance - b.distance)

  return suggestions.slice(0, maxSuggestions).map(s => s.word)
}

function isValidWord(word: string): boolean {
  const lower = word.toLowerCase()

  // Check if it's in our dictionary
  if (COMMON_WORDS.has(lower)) return true

  // Numbers are valid
  if (/^\d+$/.test(word)) return true

  // Acronyms (all caps) are valid
  if (/^[A-Z]+$/.test(word)) return true

  // Single characters are valid
  if (word.length <= 1) return true

  // Words with common suffixes - check root word
  const suffixes = [
    'ing',
    'ed',
    'er',
    'est',
    'ly',
    'tion',
    'sion',
    'ness',
    'ment',
    'able',
    'ible',
    'ful',
    'less',
    'ous',
    'ive',
    'al',
    'ial',
    'ian',
    'ance',
    'ence',
    's',
    'es',
    "'s",
    "s'"
  ]
  for (const suffix of suffixes) {
    if (lower.endsWith(suffix) && lower.length > suffix.length + 2) {
      const root = lower.slice(0, -suffix.length)
      if (COMMON_WORDS.has(root)) return true
      // Handle doubling of last consonant (e.g., "running" -> "run")
      if (root.length > 2 && root[root.length - 1] === root[root.length - 2]) {
        const shorterRoot = root.slice(0, -1)
        if (COMMON_WORDS.has(shorterRoot)) return true
      }
      // Handle 'e' dropping (e.g., "making" -> "make")
      if (COMMON_WORDS.has(root + 'e')) return true
    }
  }

  // Common prefixes - check root word
  const prefixes = [
    'un',
    're',
    'pre',
    'dis',
    'mis',
    'non',
    'over',
    'under',
    'out',
    'sub',
    'super',
    'anti',
    'auto',
    'co',
    'counter',
    'de',
    'en',
    'em',
    'ex',
    'extra',
    'fore',
    'in',
    'im',
    'il',
    'ir',
    'inter',
    'mid',
    'post',
    'pro',
    'semi',
    'trans',
    'tri',
    'ultra'
  ]
  for (const prefix of prefixes) {
    if (lower.startsWith(prefix) && lower.length > prefix.length + 2) {
      const root = lower.slice(prefix.length)
      if (COMMON_WORDS.has(root)) return true
    }
  }

  // Capitalized words (proper nouns, start of sentences) - be lenient
  if (word[0] === word[0].toUpperCase() && word.slice(1) === word.slice(1).toLowerCase()) {
    // Check if lowercase version is valid
    if (COMMON_WORDS.has(lower)) return true
    // Proper nouns are generally valid
    return true
  }

  return false
}

function isKnownMisspelling(word: string): boolean {
  return word.toLowerCase() in COMMON_MISSPELLINGS
}

function extractWords(text: string): { word: string; start: number; end: number }[] {
  const words: { word: string; start: number; end: number }[] = []
  const regex = /[a-zA-Z]+/g
  let match

  while ((match = regex.exec(text)) !== null) {
    words.push({
      word: match[0],
      start: match.index,
      end: match.index + match[0].length
    })
  }

  return words
}

export interface BrowserSpellCheckResult {
  annotations: SlideAnnotation[]
  success: boolean
}

export function checkTextWithBrowser(text: string, slideId: string, elementId: string): BrowserSpellCheckResult {
  const words = extractWords(text)
  const annotations: SlideAnnotation[] = []
  let annotationId = 1

  for (const { word, start, end } of words) {
    // Skip valid words
    if (isValidWord(word)) continue

    // Check if it's a known misspelling (high confidence)
    if (isKnownMisspelling(word)) {
      const suggestion = COMMON_MISSPELLINGS[word.toLowerCase()]
      annotations.push({
        id: `browser-ann-${slideId}-${elementId}-${annotationId++}`,
        type: 'error',
        severity: 'warning',
        category: 'spelling',
        startOffset: start,
        endOffset: end,
        originalText: word,
        message: `"${word}" is misspelled. Did you mean "${suggestion}"?`,
        suggestion,
        confidence: 0.95,
        resolved: false,
        createdAt: new Date().toISOString(),
        slideId,
        elementId
      })
      continue
    }

    // For unknown words, only flag if we have a very close suggestion (edit distance 1)
    const suggestions = findSuggestions(word, 1)
    if (suggestions.length > 0) {
      const lowerWord = word.toLowerCase()
      const suggestion = suggestions[0]
      const distance = levenshteinDistance(lowerWord, suggestion)

      // Only flag if edit distance is 1 (very likely a typo)
      if (distance === 1) {
        annotations.push({
          id: `browser-ann-${slideId}-${elementId}-${annotationId++}`,
          type: 'error',
          severity: 'warning',
          category: 'spelling',
          startOffset: start,
          endOffset: end,
          originalText: word,
          message: `"${word}" may be misspelled. Did you mean "${suggestion}"?`,
          suggestion,
          confidence: 0.7,
          resolved: false,
          createdAt: new Date().toISOString(),
          slideId,
          elementId
        })
      }
    }
  }

  return {
    annotations,
    success: true
  }
}

export function checkAllTextWithBrowser(
  slides: Array<{ id: string; elements: Array<{ id: string; type: string; content?: string }> }>
): SlideAnnotation[] {
  const allAnnotations: SlideAnnotation[] = []

  for (const slide of slides) {
    for (const element of slide.elements) {
      if (element.type === 'text' && element.content) {
        const result = checkTextWithBrowser(element.content, slide.id, element.id)
        allAnnotations.push(...result.annotations)
      }
    }
  }

  return allAnnotations
}
