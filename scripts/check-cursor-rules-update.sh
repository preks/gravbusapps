#!/bin/bash
set -e

echo "🔍 Checking for @newwork/cursor-rules updates..."

# Get current version from package.json
CURRENT_VERSION=$(node -p "require('./package.json').devDependencies['@newwork/cursor-rules']" | sed 's/[\^~]//g')
echo "📦 Current version: $CURRENT_VERSION"

# Get latest version from npm
LATEST_VERSION=$(npm view @newwork/cursor-rules version)
echo "🆕 Latest version: $LATEST_VERSION"

# Compare versions
if [ "$CURRENT_VERSION" = "$LATEST_VERSION" ]; then
  echo "✅ Already up to date!"
  exit 0
fi

echo "🔄 Update available: $CURRENT_VERSION → $LATEST_VERSION"

# Check if this is a major version change
CURRENT_MAJOR=$(echo $CURRENT_VERSION | cut -d. -f1)
LATEST_MAJOR=$(echo $LATEST_VERSION | cut -d. -f1)

if [ "$CURRENT_MAJOR" != "$LATEST_MAJOR" ]; then
  echo "⚠️  Major version change detected ($CURRENT_MAJOR → $LATEST_MAJOR)"
  echo "⚠️  Manual review required - skipping auto-update"
  echo "⚠️  Please update manually and review breaking changes"
  exit 0
fi

echo "✨ Creating update branch and PR..."

# Create update branch
BRANCH_NAME="chore/update-cursor-rules-${LATEST_VERSION}"
git checkout -b "$BRANCH_NAME"

# Update package
echo "📝 Updating package.json..."
npm install -D @newwork/cursor-rules@latest

# Sync rules
echo "🔄 Syncing cursor rules..."
npm run rules:sync

# Get changelog/release notes
CHANGELOG=$(npm view @newwork/cursor-rules@${LATEST_VERSION} --json | node -p "JSON.parse(require('fs').readFileSync('/dev/stdin')).description || 'No description available'")

# Commit changes
echo "💾 Committing changes..."
git add package.json package-lock.json .cursor/
git commit -m "chore(deps): update @newwork/cursor-rules to ${LATEST_VERSION}

- Updated from ${CURRENT_VERSION} to ${LATEST_VERSION}
- Synced cursor rules via postinstall
- Rules validated successfully

Release notes: ${CHANGELOG}

Auto-generated by scheduled pipeline"

# Push branch
echo "🚀 Pushing branch..."
git push origin "$BRANCH_NAME"

echo "✅ Branch pushed: $BRANCH_NAME"
echo ""
echo "📝 Next steps:"
echo "   1. Go to Bitbucket and create a Pull Request from: $BRANCH_NAME → develop"
echo "   2. Or run this command to create PR manually:"
echo "      Bitbucket → Pull Requests → Create Pull Request"
echo ""
echo "   PR Title: chore(deps): update @newwork/cursor-rules to ${LATEST_VERSION}"
echo ""
echo "   PR Description:"
echo "   - Updated from ${CURRENT_VERSION} to ${LATEST_VERSION}"
echo "   - Synced cursor rules automatically"
echo "   - Pipeline will validate the changes"
echo ""
echo "✅ Done!"

