#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ -z "${ANTHROPIC_API_KEY:-}" ]; then
  echo "ANTHROPIC_API_KEY is not set"
  exit 1
fi

if [ -z "${BB_REPO_TOKEN:-}" ]; then
  echo "BB_REPO_TOKEN is not set"
  exit 1
fi

if [ ! -f "plan.md" ]; then
  echo "plan.md not found. Commit plan.md to the branch before running this pipeline."
  exit 1
fi

apt-get update && apt-get install -y curl bash python3
curl -fsSL https://claude.ai/install.sh | bash
export PATH="$HOME/.local/bin:$PATH"
command -v claude

touch claude_execute_verbose.log

python3 "$SCRIPT_DIR/plan_validate.py" --repo-root .

BATCH_ID="${BATCH_ID:-1}"
eval "$(python3 "$SCRIPT_DIR/plan_parser.py" export-batch plan.md "$BATCH_ID")"

DESTINATION_BRANCH="${DESTINATION_BRANCH:-${PR_DESTINATION_BRANCH:-develop}}"

slugify() {
  echo "$1" \
    | tr '[:upper:]' '[:lower:]' \
    | sed -E 's/[^a-z0-9]+/-/g; s/^-+|-+$//g; s/-+/-/g'
}

commitify() {
  echo "$1" \
    | tr '[:upper:]' '[:lower:]' \
    | sed -E 's/[^a-z0-9 ]+/ /g; s/[ ]+/ /g; s/^ +| +$//g'
}

WORKSPACE="new-work-team"
REPO_SLUG="gravity-business-apps"
BOT_ID="xruxfctlq9qgorcxqv1h5tv0znguj2"
BASE_SHA=$(git rev-parse HEAD)
ATTEMPTS=5

BRANCH_BASE_SLUG="$(slugify "$BRANCH_BASE_SLUG")"
CLAUDE_BRANCH="feature/NO-TICKET_${BRANCH_BASE_SLUG}-claude-batch-${BATCH_ID}"
COMMIT_MSG="claude NO-TICKET: $(commitify "$BATCH_TITLE")"

git checkout -B "$CLAUDE_BRANCH"

for attempt in $(seq 1 "$ATTEMPTS"); do
  echo "=== Claude attempt $attempt ==="

  if [ "${CLAUDE_VERBOSE:-false}" = "true" ]; then
    claude -c -p "Execute plan.md exactly for batch ${BATCH_ID}.
- You must modify every file in the batch's required_files.
- Keep changes minimal and scoped to the plan.
- If verification fails, keep working until it passes." \
      --allowedTools "Bash,Read,Edit" \
      --output-format text \
      --max-budget-usd 3.00 \
      --max-turns 25 \
      --verbose \
      2> claude_execute_verbose.log || true
  else
    claude -c -p "Execute plan.md exactly for batch ${BATCH_ID}.
- You must modify every file in the batch's required_files.
- Keep changes minimal and scoped to the plan.
- If verification fails, keep working until it passes." \
      --allowedTools "Bash,Read,Edit" \
      --output-format text \
      --max-budget-usd 3.00 \
      --max-turns 25 || true
  fi

  if python3 "$SCRIPT_DIR/verify_required_files.py" plan.md "$BASE_SHA" "$BATCH_ID"; then
    echo "required_files gate passed"
    break
  fi

  if [ "$attempt" -eq "$ATTEMPTS" ]; then
    echo "required_files gate failed after $ATTEMPTS attempts"
    exit 1
  fi
done

if git diff --quiet; then
  echo "No changes to commit."
  exit 1
fi

git add -A
git config user.email "${BOT_ID}@bots.bitbucket.org"
git config user.name "claude-agent"
git commit -m "$COMMIT_MSG"

git remote set-url origin "https://x-token-auth:${BB_REPO_TOKEN}@bitbucket.org/${WORKSPACE}/${REPO_SLUG}.git"
git push -u origin "HEAD:${CLAUDE_BRANCH}"

QUERY="source.branch.name = \"${CLAUDE_BRANCH}\" AND destination.branch.name = \"${DESTINATION_BRANCH}\" AND state = \"OPEN\""
export QUERY
ENCODED_QUERY=$(python3 - <<'PY'
import os
import urllib.parse
print(urllib.parse.quote(os.environ["QUERY"]))
PY
)

PR_QUERY_STATUS=$(curl -s -o pr_query.json -w "%{http_code}" \
  --header "Authorization: Bearer ${BB_REPO_TOKEN}" \
  "https://api.bitbucket.org/2.0/repositories/${WORKSPACE}/${REPO_SLUG}/pullrequests?q=${ENCODED_QUERY}")

PR_URL=""
if [ "$PR_QUERY_STATUS" -ge 200 ] && [ "$PR_QUERY_STATUS" -lt 300 ] && [ -s pr_query.json ]; then
  PR_URL=$(python3 - <<'PY'
import json
import sys
with open("pr_query.json", "r", encoding="utf-8") as f:
    data = json.load(f)
values = data.get("values") or []
if values:
    print(values[0].get("links", {}).get("html", {}).get("href", ""))
PY
  )
fi

if [ -n "$PR_URL" ]; then
  echo "PR already exists: $PR_URL"
  exit 0
fi

PR_TITLE="Claude batch ${BATCH_ID}: ${BATCH_TITLE}"
PR_BODY="Automated changes generated by Claude agent pipeline."
PR_PAYLOAD=$(cat <<EOF
{
  "title": "${PR_TITLE}",
  "source": { "branch": { "name": "${CLAUDE_BRANCH}" } },
  "destination": { "branch": { "name": "${DESTINATION_BRANCH}" } },
  "description": "${PR_BODY}"
}
EOF
)

STATUS=$(curl -s -o pr_response.json -w "%{http_code}" \
  --request POST \
  --url "https://api.bitbucket.org/2.0/repositories/${WORKSPACE}/${REPO_SLUG}/pullrequests" \
  --header "Authorization: Bearer ${BB_REPO_TOKEN}" \
  --header "Content-Type: application/json" \
  --data "${PR_PAYLOAD}")

if [ "$STATUS" -ge 200 ] && [ "$STATUS" -lt 300 ]; then
  echo "PR created."
else
  echo "PR creation failed (status ${STATUS})."
  cat pr_response.json
  exit 1
fi
